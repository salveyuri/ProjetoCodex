type PdfStrings = (typeof pdfStrings)[SupportedLanguage];

const decimalToNumber = (value: Prisma.Decimal): number =>
  Number(value.toString());

const formatMoney = (
  value: Prisma.Decimal | number,
  strings: PdfStrings,
): string =>
  new Intl.NumberFormat(strings.currency.locale, {
    style: "currency",
    currency: strings.currency.currency,
  }).format(typeof value === "number" ? value : decimalToNumber(value));

const formatDate = (value: Date, strings: PdfStrings): string =>
  new Intl.DateTimeFormat(strings.dateLocale, {
    day: "2-digit",
    month: "2-digit",
    year: "numeric",
    timeZone: "America/Sao_Paulo",
  }).format(value);

const sanitizeFilenamePart = (value: string, fallback: string): string => {
  const COMBINING_DIACRITICS = new RegExp("[̀-ͯ]", "g");
  const normalized = value
    .normalize("NFD")
    .replace(COMBINING_DIACRITICS, "")
    .replace(/[^a-zA-Z0-9_-]+/g, "_")
    .replace(/_+/g, "_")
    .replace(/^_|_$/g, "");

  return normalized.slice(0, 48) || fallback;
};

const buildFilename = (
  quote: QuotePdfRecord,
  strings: PdfStrings,
  format: QuotePdfFormat,
): string => {
  const shortId = quote.id.slice(0, 8);
  const customer = sanitizeFilenamePart(quote.customerName, strings.filenameFallback);
  const suffix = format === "SUMMARY" ? strings.filenameSummarySuffix : "";

  return `${strings.filenamePrefix}_${shortId}_${customer}${suffix}.pdf`;
};

const collectDocument = (doc: PDFKit.PDFDocument): Promise<Buffer> => {
  const chunks: Buffer[] = [];

  doc.on("data", (chunk: Buffer | Uint8Array) => {
    chunks.push(Buffer.from(chunk));
  });

  return new Promise((resolve, reject) => {
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);
  });
};

const getLogoBuffer = (logoUrl: string | null): Buffer | null => {
  if (!logoUrl) {
    return null;
  }

  const dataUri = /^data:image\/(?:png|jpe?g);base64,(.+)$/i.exec(logoUrl);

  if (!dataUri) {
    return null;
  }

  try {
    return Buffer.from(dataUri[1], "base64");
  } catch {
    return null;
  }
};

const drawLogo = (
  doc: PDFKit.PDFDocument,
  quote: QuotePdfRecord,
  x: number,
  y: number,
): void => {
  const logoBuffer = getLogoBuffer(quote.company.logoUrl);

  if (logoBuffer) {
    try {
      doc.image(logoBuffer, x, y, { fit: [58, 58] });
      return;
    } catch {
      // Falls back to monogram when an uploaded image is not readable.
    }
  }

  const initials = quote.company.name
    .split(/\s+/)
    .filter(Boolean)
    .slice(0, 2)
    .map((part) => part[0]?.toUpperCase())
    .join("");

  doc
    .roundedRect(x, y, 58, 58, 12)
    .fill(colors.primary)
    .fillColor(colors.white)
    .font("Helvetica-Bold")
    .fontSize(18)
    .text(initials || "3D", x, y + 20, {
      width: 58,
      align: "center",
    });
};

const drawKeyValue = (
  doc: PDFKit.PDFDocument,
  label: string,
  value: string,
  x: number,
  y: number,
  width: number,
): void => {
  doc
    .fillColor(colors.muted)
    .font("Helvetica")
    .fontSize(8)
    .text(label.toUpperCase(), x, y, { width });
  doc
    .fillColor(colors.ink)
    .font("Helvetica-Bold")
    .fontSize(10)
    .text(value, x, y + 12, { width });
};

// Returns the y coordinate where the header's divider line landed, so the
// caller can flow the rest of the page below it — the left column's height
// varies with how many of taxId/phone/address the company has filled in.
const drawHeader = (
  doc: PDFKit.PDFDocument,
  quote: QuotePdfRecord,
  strings: PdfStrings,
): number => {
  const margin = 48;
  const rightX = 365;

  drawLogo(doc, quote, margin, margin);

  doc
    .fillColor(colors.ink)
    .font("Helvetica-Bold")
    .fontSize(18)
    .text(quote.company.name, margin + 74, margin + 2, { width: 260 });

  const infoLines = [
    `${strings.contactLabel} ${quote.company.user.email}`,
    quote.company.taxId ? `${strings.taxIdLabel} ${quote.company.taxId}` : strings.taxIdUnknown,
  ];

  if (quote.company.phone) {
    infoLines.push(`${strings.phoneLabel} ${quote.company.phone}`);
  }

  if (quote.company.address) {
    infoLines.push(quote.company.address);
  }

  const lineHeight = 13;

  doc.fillColor(colors.muted).font("Helvetica").fontSize(9);
  infoLines.forEach((line, index) => {
    doc.text(line, margin + 74, margin + 28 + index * lineHeight, { width: 260 });
  });

  doc
    .font("Helvetica-Bold")
    .fontSize(22)
    .fillColor(colors.primaryDark)
    .text(strings.quoteHeading, rightX, margin, { width: 180, align: "right" });
  doc
    .font("Helvetica")
    .fontSize(9)
    .fillColor(colors.muted)
    .text(`#${quote.id.slice(0, 8).toUpperCase()}`, rightX, margin + 28, {
      width: 180,
      align: "right",
    })
    .text(`${strings.statusLabel} ${quote.status}`, rightX, margin + 42, {
      width: 180,
      align: "right",
    });

  const leftBottom = margin + 28 + infoLines.length * lineHeight + 8;
  const dividerY = Math.max(128, leftBottom);

  doc
    .moveTo(margin, dividerY)
    .lineTo(doc.page.width - margin, dividerY)
    .lineWidth(2)
    .strokeColor(colors.primary)
    .stroke();

  return dividerY;
};

const drawCustomerBlock = (
  doc: PDFKit.PDFDocument,
  quote: QuotePdfRecord,
  y: number,
  strings: PdfStrings,
): number => {
  const margin = 48;
  const width = doc.page.width - margin * 2;

  doc.roundedRect(margin, y, width, 72, 10).fill(colors.soft);
  drawKeyValue(doc, strings.clientLabel, quote.customerName, margin + 18, y + 16, 210);
  drawKeyValue(
    doc,
    strings.issuedLabel,
    formatDate(quote.createdAt, strings),
    margin + 248,
    y + 16,
    100,
  );
  drawKeyValue(
    doc,
    strings.validUntilLabel,
    formatDate(quote.validUntil, strings),
    margin + 365,
    y + 16,
    100,
  );

  return y + 98;
};

const buildTableColumns = (strings: PdfStrings) => [
  { label: strings.columns.piece, width: 132 },
  { label: strings.columns.qty, width: 38 },
  { label: strings.columns.material, width: 105 },
  { label: strings.columns.machine, width: 88 },
  { label: strings.columns.weightTime, width: 62 },
  { label: strings.columns.value, width: 74 },
];

const drawItemsHeader = (
  doc: PDFKit.PDFDocument,
  y: number,
  tableColumns: ReturnType<typeof buildTableColumns>,
): number => {
  const margin = 48;
  let x = margin;

  doc.roundedRect(margin, y, doc.page.width - margin * 2, 26, 7).fill(colors.primary);

  for (const column of tableColumns) {
    doc
      .fillColor(colors.white)
      .font("Helvetica-Bold")
      .fontSize(8)
      .text(column.label.toUpperCase(), x + 8, y + 9, {
        width: column.width - 12,
      });
    x += column.width;
  }

  return y + 30;
};

const ensurePageSpace = (
  doc: PDFKit.PDFDocument,
  y: number,
  neededHeight: number,
  tableColumns?: ReturnType<typeof buildTableColumns>,
): number => {
  const bottom = doc.page.height - 70;

  if (y + neededHeight <= bottom) {
    return y;
  }

  doc.addPage();
  return tableColumns ? drawItemsHeader(doc, 48, tableColumns) : 48;
};

const drawItemsTable = (
  doc: PDFKit.PDFDocument,
  quote: QuotePdfRecord,
  y: number,
  strings: PdfStrings,
): number => {
  const tableColumns = buildTableColumns(strings);
  let currentY = drawItemsHeader(doc, y, tableColumns);
  const margin = 48;

  for (const [index, item] of quote.printItems.entries()) {
    const rowHeight = Math.max(
      46,
      doc.heightOfString(item.modelName, {
        width: tableColumns[0].width - 14,
      }) + 22,
    );

    currentY = ensurePageSpace(doc, currentY, rowHeight, tableColumns);

    if (index % 2 === 0) {
      doc
        .rect(margin, currentY - 3, doc.page.width - margin * 2, rowHeight)
        .fill("#FBFCFF");
    }

    let x = margin;
    const material = `${item.material.brand} ${item.material.color}`;
    const metrics = `${decimalToNumber(item.materialWeightGrams).toFixed(0)} g\n${decimalToNumber(
      item.estimatedPrintTimeHours,
    ).toFixed(2)} h`;
    const values = [
      item.modelName,
      "1",
      material,
      item.machine.name,
      metrics,
      formatMoney(item.finalPrice, strings),
    ];

    values.forEach((value, columnIndex) => {
      const column = tableColumns[columnIndex];
      doc
        .fillColor(columnIndex === 5 ? colors.ink : colors.muted)
        .font(columnIndex === 0 || columnIndex === 5 ? "Helvetica-Bold" : "Helvetica")
        .fontSize(columnIndex === 5 ? 9 : 8)
        .text(value, x + 8, currentY + 10, {
          width: column.width - 12,
          align: columnIndex === 5 ? "right" : "left",
        });
      x += column.width;
    });

    doc
      .moveTo(margin, currentY + rowHeight - 3)
      .lineTo(doc.page.width - margin, currentY + rowHeight - 3)
      .lineWidth(0.5)
      .strokeColor(colors.line)
      .stroke();

    currentY += rowHeight;
  }

  return currentY + 18;
};

const drawFinancialSummary = (
  doc: PDFKit.PDFDocument,
  quote: QuotePdfRecord,
  y: number,
  strings: PdfStrings,
): number => {
  const margin = 48;
  const boxWidth = 220;
  const x = doc.page.width - margin - boxWidth;
  // totalAmount already has adjustmentAmount folded in (see
  // CalculationService#calculateAggregate) — subtotal is what it was
  // before "Desconto/Acréscimo" was applied.
  const subtotal = quote.totalAmount.sub(quote.adjustmentAmount);
  const adjustmentLabel =
    quote.adjustmentType === "SURCHARGE" ? strings.surcharge : strings.discounts;

  const currentY = ensurePageSpace(doc, y, 126);
  doc.roundedRect(x, currentY, boxWidth, 126, 10).fill(colors.soft);

  const rows = [
    [strings.subtotal, formatMoney(subtotal, strings)],
    [adjustmentLabel, formatMoney(quote.adjustmentAmount, strings)],
    [strings.total, formatMoney(quote.totalAmount, strings)],
  ] as const;

  rows.forEach(([label, value], index) => {
    const rowY = currentY + 18 + index * 31;
    doc
      .fillColor(index === 2 ? colors.primaryDark : colors.muted)
      .font(index === 2 ? "Helvetica-Bold" : "Helvetica")
      .fontSize(index === 2 ? 12 : 9)
      .text(label, x + 16, rowY, { width: 100 });
    doc
      .fillColor(index === 2 ? colors.primaryDark : colors.ink)
      .font("Helvetica-Bold")
      .fontSize(index === 2 ? 15 : 10)
      .text(value, x + 100, rowY - (index === 2 ? 2 : 0), {
        width: 104,
        align: "right",
      });
  });

  doc
    .fillColor(colors.muted)
    .font("Helvetica")
    .fontSize(8)
    .text(
      `${strings.formulaApplied} ${
        quote.formula?.name ?? quote.systemFormula?.name ?? strings.defaultFormulaName
      }`,
      margin,
      currentY + 12,
      { width: x - margin - 18 },
    )
    .text(
      strings.totalWeight(decimalToNumber(quote.totalWeightGrams).toFixed(2)),
      margin,
      currentY + 30,
      { width: x - margin - 18 },
    )
    .text(
      strings.totalTime(decimalToNumber(quote.totalPrintHours).toFixed(2)),
      margin,
      currentY + 46,
      { width: x - margin - 18 },
    );

  return currentY + 148;
};

// SUMMARY mode's version of drawFinancialSummary — no subtotal/discounts
// rows and no formula/weight/time side notes, by design (a client who
// shouldn't see the cost breakdown, only the bottom line). totalAmount
// already has any "Desconto/Acréscimo" folded in either way.
const drawFinancialSummarySimple = (
  doc: PDFKit.PDFDocument,
  quote: QuotePdfRecord,
  y: number,
  strings: PdfStrings,
): number => {
  const margin = 48;
  const boxWidth = 220;
  const x = doc.page.width - margin - boxWidth;
  const boxHeight = 56;

  const currentY = ensurePageSpace(doc, y, boxHeight);
  doc.roundedRect(x, currentY, boxWidth, boxHeight, 10).fill(colors.soft);

  const rowY = currentY + 20;
  doc
    .fillColor(colors.primaryDark)
    .font("Helvetica-Bold")
    .fontSize(12)
    .text(strings.total, x + 16, rowY, { width: 100 });
  doc
    .fillColor(colors.primaryDark)
    .font("Helvetica-Bold")
    .fontSize(15)
    .text(formatMoney(quote.totalAmount, strings), x + 100, rowY - 2, {
      width: 104,
      align: "right",
    });

  return currentY + boxHeight + 22;
};

// Company.customTerms/customTermsEn (raw multi-line free text, one term per
// line) override the built-in localized terms when the company filled in
// the matching language via Settings > Perfil. Deliberately does NOT fall
// back to the other language's custom text if only one is set — mixing a
// company's own pt-BR wording into an English PDF (or vice versa) would be
// worse than just falling back to the standard localized terms.
const resolveTerms = (
  quote: QuotePdfRecord,
  strings: PdfStrings,
  language: SupportedLanguage,
): string[] => {
  const custom = (language === "en" ? quote.company.customTermsEn : quote.company.customTerms)?.trim();

  if (!custom) {
    return [...strings.terms];
  }

  return custom
    .split("\n")
    .map((line) => line.trim())
    .filter(Boolean);
};

const drawTerms = (
  doc: PDFKit.PDFDocument,
  quote: QuotePdfRecord,
  y: number,
  strings: PdfStrings,
  language: SupportedLanguage,
): void => {
  const margin = 48;
  const currentY = ensurePageSpace(doc, y, 120);

  doc
    .fillColor(colors.ink)
    .font("Helvetica-Bold")
    .fontSize(11)
    .text(strings.termsHeading, margin, currentY);
  doc
    .fillColor(colors.muted)
    .font("Helvetica")
    .fontSize(8.5)
    .text(
      [
        ...resolveTerms(quote, strings, language),
        strings.validUntilNote(formatDate(quote.validUntil, strings)),
      ].join("\n"),
      margin,
      currentY + 18,
      { width: doc.page.width - margin * 2, lineGap: 4 },
    );

  doc
    .moveTo(margin, doc.page.height - 46)
    .lineTo(doc.page.width - margin, doc.page.height - 46)
    .lineWidth(0.5)
    .strokeColor(colors.line)
    .stroke();
  doc
    .fillColor(colors.muted)
    .fontSize(7)
    .text(strings.footer(quote.company.name), margin, doc.page.height - 34, {
      width: doc.page.width - margin * 2,
      align: "center",
    });
};

const renderQuotePdf = (
  doc: PDFKit.PDFDocument,
  quote: QuotePdfRecord,
  strings: PdfStrings,
  language: SupportedLanguage,
  format: QuotePdfFormat,
): void => {
  const headerBottom = drawHeader(doc, quote, strings);
  let y = drawCustomerBlock(doc, quote, headerBottom + 22, strings);

  if (format === "SUMMARY") {
    y = drawFinancialSummarySimple(doc, quote, y + 4, strings);
  } else {
    doc
      .fillColor(colors.ink)
      .font("Helvetica-Bold")
      .fontSize(13)
      .text(strings.sectionItems, 48, y);

    y = drawItemsTable(doc, quote, y + 22, strings);
    y = drawFinancialSummary(doc, quote, y, strings);
  }

  drawTerms(doc, quote, y, strings, language);
};

export class QuotePdfService {
  async generate(
    companyId: string,
    quoteId: string,
    format: QuotePdfFormat = "FULL",
  ): Promise<QuotePdfResult> {
    const quote = await prisma.quote.findFirst({
      where: { id: quoteId, companyId },
      include: quotePdfInclude,
    });

    if (!quote) {
      // "Access denied." on purpose — see Contextos/Conhecimento.md.
      throw new AppError("Access denied.", 403, "QUOTE_FORBIDDEN");
    }

    const language = quote.company.user.language as SupportedLanguage;
    const strings = pdfStrings[language];

    const doc = new PDFDocument({
      size: "A4",
      margin: 48,
      bufferPages: true,
      info: {
        Title: `${strings.docTitlePrefix} ${quote.id.slice(0, 8).toUpperCase()}`,
        Author: quote.company.name,
        Subject: `${strings.docSubjectPrefix} ${quote.customerName}`,
        Creator: "3D Budget SaaS",
      },
    });
    const pdfBuffer = collectDocument(doc);

    renderQuotePdf(doc, quote, strings, language, format);
    doc.end();

    return {
      buffer: await pdfBuffer,
      filename: buildFilename(quote, strings, format),
    };
  }
}

export const quotePdfService = new QuotePdfService();
